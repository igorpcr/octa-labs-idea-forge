-- Canonical catalog registry; SKUs registered but not enabled for checkout.
create table if not exists public.octa_sku_registry (
 sku text primary key,
 title text not null,
 enabled boolean not null default false,
 price_status text not null default 'pending_price' check(price_status in ('pending_price','verified')),
 shipping_status text not null default 'manual_review' check(shipping_status in ('manual_review','eligible','ineligible')),
 unit_cents bigint check(unit_cents > 0),
 created_at timestamptz not null default now(),
 constraint octa_sku_price_gate check(not enabled or (price_status='verified' and unit_cents is not null))
);
alter table public.octa_sku_registry enable row level security;
